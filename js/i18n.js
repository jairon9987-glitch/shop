const KEY = 'vortx_lang';
export function currentLang() {
  try { return localStorage.getItem(KEY) || 'es'; } catch (e) { return 'es'; }
}
export function t(key, params) {
  const lang = currentLang();
  let v = (I18N[lang] && I18N[lang][key]) || (I18N.en && I18N.en[key]) || ES[key] || key;
  if (params) for (const [k, val] of Object.entries(params)) v = v.split('{' + k + '}').join(String(val));
  return v;
}
export function applyI18n() {
  const lang = currentLang();
  const dict = I18N[lang] || ES;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const v = dict[el.dataset.i18n] || (I18N.en && I18N.en[el.dataset.i18n]) || ES[el.dataset.i18n];
    if (v) el.textContent = v;
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const v = dict[el.dataset.i18nPh] || (I18N.en && I18N.en[el.dataset.i18nPh]) || ES[el.dataset.i18nPh];
    if (v) el.setAttribute('placeholder', v);
  });
  const meta = LANGS.find(l => l.code === lang);
  document.documentElement.lang = lang;
  document.documentElement.dir = meta && meta.rtl ? 'rtl' : 'ltr';
  const cur = document.getElementById('langCur');
  if (cur && meta) cur.textContent = meta.name;
  document.querySelectorAll('#langList .lang-opt').forEach(b =>
    b.classList.toggle('active', b.dataset.lang === lang));
}
export function setLang(code) {
  if (!LANGS.some(l => l.code === code)) code = 'es';
  try { localStorage.setItem(KEY, code); } catch (e) {}
  applyI18n();
  window.dispatchEvent(new CustomEvent('vortx-lang', { detail: { lang: code } }));
}
export function initI18n() {
  const list = document.getElementById('langList');
  const btn = document.getElementById('langBtn');
  const panel = document.getElementById('langPanel');
  const search = document.getElementById('langSearch');
  if (list && btn && panel) {
    const paint = (q) => {
      const nq = (q || '').toLowerCase();
      list.innerHTML = LANGS
        .filter(l => !nq || l.name.toLowerCase().includes(nq) || l.code.includes(nq))
        .map(l => '<button type="button" class="lang-opt' + (l.code === currentLang() ? ' active' : '') + '" data-lang="' + l.code + '" role="option">' +
          '<span class="lang-code">' + l.code.toUpperCase() + '</span><span class="lang-name">' + l.name + '</span>' +
          '<span class="lang-check">✓</span></button>').join('');
      list.querySelectorAll('.lang-opt').forEach(b => b.addEventListener('click', () => {
        setLang(b.dataset.lang);
        panel.classList.add('hidden');
        btn.setAttribute('aria-expanded', 'false');
      }));
    };
    paint('');
    btn.addEventListener('click', (e) => {
      e.stopPropagation();
      const open = panel.classList.toggle('hidden') === false;
      btn.setAttribute('aria-expanded', String(open));
      if (open && search) { search.value = ''; paint(''); setTimeout(() => search.focus(), 30); }
    });
    panel.addEventListener('click', (e) => e.stopPropagation());
    document.addEventListener('click', () => { panel.classList.add('hidden'); btn.setAttribute('aria-expanded', 'false'); });
    if (search) search.addEventListener('input', () => paint(search.value));
  }
  applyI18n();
}

